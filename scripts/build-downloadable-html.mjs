import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = process.cwd();
const sourcePath = resolve(root, 'index.html');
const outputPath = resolve(root, 'HEARD_app_context.html');
const caregiverOutputPath = resolve(root, 'HEARD_caregiver.html');

const [html, css, capsuleScript, appScript] = await Promise.all([
  readFile(sourcePath, 'utf8'),
  readFile(resolve(root, 'styles.css'), 'utf8'),
  readFile(resolve(root, 'heard-capsule-reveal.js'), 'utf8'),
  readFile(resolve(root, 'script.js'), 'utf8')
]);

const safeScript = (source) => source.replaceAll('</script', '<\\/script');

const bundle = (sourceHtml, generatedNote) => sourceHtml
  .replace(
    '    <link rel="stylesheet" href="./styles.css" />',
    `    <!-- Styles inlined for a portable source/context file. Visual assets remain in ./public. -->\n    <style>\n${css}\n    </style>`
  )
  .replace(
    '    <script src="./heard-capsule-reveal.js"></script>',
    `    <script>\n${safeScript(capsuleScript)}\n    </script>`
  )
  .replace(
    '    <script src="./script.js"></script>',
    `    <script>\n${safeScript(appScript)}\n    </script>`
  )
  .replace(
    '<!doctype html>',
    `<!doctype html>\n<!-- ${generatedNote} -->`
  );

const bundled = bundle(html, 'Generated by npm run build:html. Edit index.html, styles.css, or script.js instead of this file.');
const caregiverSource = html
  .replace('<title>HEARD · IBD Companion</title>', '<title>HEARD · Caregiver Companion</title>')
  .replace('<body>', '<body class="caregiver-app" data-app-role="caregiver">')
  .replace('<h1 id="champion-name">Evan Koh</h1>', '<h1 id="champion-name">Caregiver</h1>')
  .replace('<p id="champion-condition">Your IBD Companion</p>', '<p id="champion-condition">Supporting Evan Koh</p>')
  .replace('<div class="avatar avatar--user" aria-hidden="true"><span>👦🏻</span></div>', '<div class="avatar avatar--user" aria-hidden="true"><span>🧑🏽</span></div>');
const caregiverBundled = bundle(caregiverSource, 'Caregiver presentation build generated by npm run build:html.');

await Promise.all([
  writeFile(outputPath, bundled, 'utf8'),
  writeFile(caregiverOutputPath, caregiverBundled, 'utf8')
]);
console.log(`Created ${outputPath}`);
console.log(`Created ${caregiverOutputPath}`);
