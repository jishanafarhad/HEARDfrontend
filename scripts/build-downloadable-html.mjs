import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = process.cwd();
const sourcePath = resolve(root, 'index.html');
const outputPath = resolve(root, 'HEARD_app_context.html');

const [html, css, capsuleScript, appScript] = await Promise.all([
  readFile(sourcePath, 'utf8'),
  readFile(resolve(root, 'styles.css'), 'utf8'),
  readFile(resolve(root, 'heard-capsule-reveal.js'), 'utf8'),
  readFile(resolve(root, 'script.js'), 'utf8')
]);

const safeScript = (source) => source.replaceAll('</script', '<\\/script');

const bundled = html
  .replace(
    '    <link rel="stylesheet" href="./styles.css" />',
    `    <!-- Styles inlined for a portable source/context file. Visual assets remain in ./public. -->\n    <style>\n${css}\n    </style>`
  )
  .replace(
    '    <script src="./heard-capsule-reveal.js"></script>',
    `    <script>\n${safeScript(capsuleScript)}\n    </script>`
  )
  .replace(
    '    <script src="./script.js"></script>',
    `    <script>\n${safeScript(appScript)}\n    </script>`
  )
  .replace(
    '<!doctype html>',
    '<!doctype html>\n<!-- Generated by npm run build:html. Edit index.html, styles.css, or script.js instead of this file. -->'
  );

await writeFile(outputPath, bundled, 'utf8');
console.log(`Created ${outputPath}`);
